/**
 * Every pixel in the game, as rows of PALETTE keys. '.' is transparent.
 *
 * Authored at 1x against the 32 px tile grid and checked at 1x on both a dark
 * and a pale backdrop, because a sprite that only reads on black is a sprite
 * that disappears over ice and water.
 *
 * Two rules run through the whole sheet and are worth stating before the data:
 *   - Hazards own red. Nothing decorative uses 'E' or 'x', so a red pixel is
 *     always a promise that the thing will kill you.
 *   - Every free-standing entity carries a one-pixel '0' outline, so it stays
 *     readable against moss, rust, ice and the void alike.
 *
 * Sprites are drawn centred on the entity origin unless ax/ay say otherwise.
 * Only the player sets them: its 11x21 hitbox is not centred in its 22x22
 * frame.
 *
 * There are deliberately no spike sprites here. Spikes are rendered from the
 * same per-pixel masks the simulation collides against (SPIKE_MASKS in
 * registry/tileMaterials.ts), so their art cannot drift from their hitbox.
 */


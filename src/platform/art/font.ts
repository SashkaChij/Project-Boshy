/**
 * A 6x8 bitmap font with a full Russian alphabet.
 *
 * Cyrillic is the entire reason this font exists: retro pixel fonts almost
 * never ship it, and Д Ж Щ Ю Ы turn to mush at this size unless they are
 * drawn deliberately. The twelve capitals that are shape-identical to Latin
 * (А В Е К М Н О Р С Т У Х) share the Latin rows outright, so they cannot
 * drift apart, and the effort went into the ~54 genuinely different letters.
 *
 * METRICS. The cell is 6 wide and 8 tall; column 5 is the inter-character
 * gap, so glyphs are drawn 5 wide. Caps and digits occupy rows 0..6 with the
 * baseline on row 6, x-height letters occupy rows 2..6, and descenders reach
 * row 7. The breve of Й/й and the dieresis of Ё/ё sit on row 0 with the
 * letter compressed into rows 2..6 -- at 5x7 there is no other way to fit an
 * accent and still be able to read the letter under it.
 *
 * ENCODING. Each glyph is 8 row bitmasks and bit 5 is the LEFTMOST pixel,
 * which is why every row is written as a binary literal: the source is the
 * picture. 0b011100 is a three-pixel bar starting one pixel in.
 */
